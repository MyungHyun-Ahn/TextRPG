using System.Globalization;
using System.Text;

internal sealed record SGeneratedFile(string RelativePath, string Content);

internal static class FGameDataGenerators
{
    public static IReadOnlyList<SGeneratedFile> Generate(
        IReadOnlyList<FGameDataTable> tables,
        IReadOnlyDictionary<string, FGameDataEnumDefinition> enumDefinitions)
    {
        var files = new List<SGeneratedFile>
        {
            new(".gamedata-output", "GameDataGenerator owned output v1\n"),
        };

        FGameDataEnumDefinition[] clientEnums = enumDefinitions.Values
            .Where(definition => definition.IsIncludedOnClient)
            .OrderBy(definition => definition.Name, StringComparer.Ordinal)
            .ToArray();
        if (clientEnums.Length != 0)
        {
            files.Add(new SGeneratedFile("Cpp/Common/GameDataEnums.g.h", GenerateCppEnums(clientEnums)));
        }

        foreach (FGameDataTable table in tables
            .Where(table => !FGameDataEnumCatalog.IsDefinitionTable(table) && table.IsIncludedOnClient)
            .OrderBy(table => table.Name, StringComparer.Ordinal))
        {
            files.Add(new SGeneratedFile(
                $"Cpp/{table.Name}/{table.Name}Data.g.h",
                GenerateCppTable(table)));
            files.Add(new SGeneratedFile(
                $"Data/Client/{table.Name}.yaml",
                GenerateClientDataYaml(table)));
        }

        // 실제로 내보낸 파일 목록만 사용한다. 기존 출력 디렉터리의 폐기 파일은 참조하지 않는다.
        files.Add(new SGeneratedFile("Cpp/GameDataAll.h", GenerateCppUmbrella(files)));
        return files;
    }

    private static string GenerateCppUmbrella(IReadOnlyList<SGeneratedFile> files)
    {
        var builder = new StringBuilder();
        builder.AppendLine("#pragma once");
        builder.AppendLine();
        builder.AppendLine("// Generated by GameDataGenerator. Do not edit.");
        builder.AppendLine("#include <array>");
        builder.AppendLine("#include <cstdint>");
        builder.AppendLine("#include <string>");
        // Generate가 Enum을 먼저, 테이블을 Ordinal 순서로 내보낸다.
        foreach (SGeneratedFile file in files.Where(file =>
            file.RelativePath.StartsWith("Cpp/", StringComparison.Ordinal) &&
            file.RelativePath.EndsWith(".g.h", StringComparison.Ordinal)))
        {
            builder.Append("#include \"").Append(file.RelativePath[4..]).AppendLine("\"");
        }
        return NormalizeNewLines(builder.ToString());
    }

    private static string GenerateClientDataYaml(FGameDataTable table)
    {
        FGameDataField[] fields = table.Fields
            .Where(field => field.IsIncludedOnClient && field.Type != null)
            .OrderBy(field => field.ColumnNumber)
            .ToArray();
        FGameDataField keyField = table.PrimaryKey
            ?? throw new InvalidOperationException($"Client table has no primary key: {table.Name}");
        var builder = new StringBuilder("# TextRPG.GameData 1\n");
        foreach (FGameDataRow row in table.Rows)
        {
            row.Values.TryGetValue(keyField.Name, out object? keyValue);
            string keyPart = keyValue == null
                ? string.Empty
                : keyField.Type!.Kind is EGameDataScalarKind.String or EGameDataScalarKind.Enum
                    ? Convert.ToString(keyValue, CultureInfo.InvariantCulture) ?? string.Empty
                    : FGameDataText.FormatScalar(keyValue, keyField.Type!);
            string key = table.Name + keyPart;
            builder.Append(QuoteYaml(key)).AppendLine(":");
            foreach (FGameDataField field in fields)
            {
                row.Values.TryGetValue(field.Name, out object? value);
                builder.Append("  ").Append(QuoteYaml(field.Name)).Append(": ")
                    .AppendLine(FormatYamlScalar(value, field.Type!));
            }
        }
        return NormalizeNewLines(builder.ToString());
    }

    private static string FormatYamlScalar(object? value, FGameDataType type)
    {
        if (value == null)
        {
            return "null";
        }
        if (type.Kind is EGameDataScalarKind.String or EGameDataScalarKind.Enum)
        {
            return QuoteYaml(Convert.ToString(value, CultureInfo.InvariantCulture) ?? string.Empty);
        }
        if (type.Kind == EGameDataScalarKind.Bool)
        {
            return (bool)value ? "true" : "false";
        }
        return FGameDataText.FormatScalar(value, type);
    }

    private static string QuoteYaml(string value)
    {
        var builder = new StringBuilder(value.Length + 2);
        builder.Append('"');
        foreach (Rune rune in value.EnumerateRunes())
        {
            switch (rune.Value)
            {
                case 0x00: builder.Append("\\0"); break;
                case 0x07: builder.Append("\\a"); break;
                case 0x08: builder.Append("\\b"); break;
                case 0x09: builder.Append("\\t"); break;
                case 0x0A: builder.Append("\\n"); break;
                case 0x0B: builder.Append("\\v"); break;
                case 0x0C: builder.Append("\\f"); break;
                case 0x0D: builder.Append("\\r"); break;
                case 0x1B: builder.Append("\\e"); break;
                case '\\': builder.Append("\\\\"); break;
                case '"': builder.Append("\\\""); break;
                default:
                    if (rune.Value < 0x20 || rune.Value is >= 0x7F and <= 0x9F)
                    {
                        builder.Append("\\u").Append(rune.Value.ToString("X4", CultureInfo.InvariantCulture));
                    }
                    else
                    {
                        builder.Append(rune.ToString());
                    }
                    break;
            }
        }
        return builder.Append('"').ToString();
    }

    private static string GenerateCppEnums(IReadOnlyList<FGameDataEnumDefinition> definitions)
    {
        var builder = new StringBuilder();
        builder.AppendLine("#pragma once");
        builder.AppendLine();
        builder.AppendLine("// Generated by GameDataGenerator. Do not edit.");
        builder.AppendLine("// 소비 번역 단위: <cstdint>의 ::std 정수형을 이 헤더보다 먼저 포함한다.");
        builder.AppendLine("// 이 헤더는 열거형을 사용하는 데이터 헤더보다 먼저 명시적으로 포함한다.");
        builder.AppendLine("namespace GameData::Common");
        builder.AppendLine("{");
        for (int definitionIndex = 0; definitionIndex < definitions.Count; ++definitionIndex)
        {
            FGameDataEnumDefinition definition = definitions[definitionIndex];
            builder.AppendLine($"\tenum class E{definition.Name} : {RenderCppEnumUnderlyingType(definition.UnderlyingType)}");
            builder.AppendLine("\t{");
            for (int valueIndex = 0; valueIndex < definition.Values.Count; ++valueIndex)
            {
                SEnumValue value = definition.Values[valueIndex];
                string comma = valueIndex + 1 == definition.Values.Count ? string.Empty : ",";
                builder.AppendLine($"\t\t{value.Name} = {value.NumericValue!.Value}{comma}");
            }
            builder.AppendLine("\t};");
            if (definitionIndex + 1 != definitions.Count)
            {
                builder.AppendLine();
            }
        }
        builder.AppendLine("}");
        return NormalizeNewLines(builder.ToString());
    }

    private static string GenerateCppTable(FGameDataTable table)
    {
        IReadOnlyList<FGameDataField> fields = table.Fields.Where(field => field.IsIncludedOnClient).ToArray();
        FGameDataField key = table.PrimaryKey!;
        string rowName = $"S{table.Name}Data";

        bool hasEnums = fields.Any(field => field.Type!.Kind == EGameDataScalarKind.Enum);

        var builder = new StringBuilder();
        builder.AppendLine("#pragma once");
        builder.AppendLine();
        builder.AppendLine("// Generated by GameDataGenerator. Do not edit.");
        builder.AppendLine("// 소비 번역 단위: <array>, <cstdint>, <string>의 ::std 타입을 이 헤더보다 먼저 포함한다.");
        if (hasEnums)
        {
            builder.AppendLine("// Common/GameDataEnums.g.h를 이 헤더보다 먼저 명시적으로 포함한다.");
        }
        builder.AppendLine($"namespace GameData::{table.Name}");
        builder.AppendLine("{");
        builder.AppendLine($"\tstruct {rowName} final");
        builder.AppendLine("\t{");
        builder.AppendLine($"\t\tusing KeyType = {RenderCppType(key.Type!)};");
        foreach (FGameDataField field in fields)
        {
            string memberName = FGameDataNaming.ToCppMemberName(table.Name, field.Name);
            builder.AppendLine($"\t\t{RenderCppType(field.Type!)} {memberName}{{}};");
        }
        builder.AppendLine("\t};");

        builder.AppendLine("}");
        return NormalizeNewLines(builder.ToString());
    }

    private static string RenderCppType(FGameDataType type)
    {
        return type.Kind switch
        {
            EGameDataScalarKind.Bool => "bool",
            EGameDataScalarKind.Int32 => "::std::int32_t",
            EGameDataScalarKind.UInt32 => "::std::uint32_t",
            EGameDataScalarKind.Int64 => "::std::int64_t",
            EGameDataScalarKind.UInt64 => "::std::uint64_t",
            EGameDataScalarKind.Float => "float",
            EGameDataScalarKind.Double => "double",
            EGameDataScalarKind.String => "::std::wstring",
            EGameDataScalarKind.Enum => $"::GameData::Common::E{type.EnumName}",
            _ => throw new ArgumentOutOfRangeException(nameof(type)),
        };
    }

    private static string RenderCppEnumUnderlyingType(EGameDataEnumUnderlyingType underlyingType) => underlyingType switch
    {
        EGameDataEnumUnderlyingType.UInt8 => "::std::uint8_t",
        EGameDataEnumUnderlyingType.UInt16 => "::std::uint16_t",
        EGameDataEnumUnderlyingType.Int32 => "::std::int32_t",
        EGameDataEnumUnderlyingType.UInt32 => "::std::uint32_t",
        _ => throw new ArgumentOutOfRangeException(nameof(underlyingType)),
    };

    private static string NormalizeNewLines(string text) => text.Replace("\r\n", "\n", StringComparison.Ordinal);
}
